-- TABLE: device_registrations
-- Tracks all device activations for each license
-- =====================================================
CREATE TABLE IF NOT EXISTS device_registrations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  license_id INTEGER NOT NULL REFERENCES licenses(id) ON DELETE CASCADE,
  browser_instance_id VARCHAR(36) NOT NULL UNIQUE,  -- UUID v4 from client
  activated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  deactivated_at TIMESTAMP,  -- NULL = active, NOT NULL = deactivated
  created_at TIMESTAMP DEFAULT NOW(),
  updated_at TIMESTAMP DEFAULT NOW()
);

-- Index for license_id lookups (find all devices for a license)
CREATE INDEX IF NOT EXISTS idx_device_registrations_license_id ON device_registrations(license_id);

-- Index for browser_instance_id lookups (validation checks)
CREATE INDEX IF NOT EXISTS idx_device_registrations_browser_id ON device_registrations(browser_instance_id);

-- Partial index for active registrations only (performance optimization)
CREATE INDEX IF NOT EXISTS idx_device_registrations_active ON device_registrations(license_id, activated_at)
WHERE deactivated_at IS NULL;

-- Composite index for validation queries (license + browser + active status)
